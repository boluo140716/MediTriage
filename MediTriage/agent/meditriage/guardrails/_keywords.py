import re

HIGH_RISK_KEYWORDS = (
    "胸痛", "呼吸困难", "昏厥", "剧烈头痛", "心悸", "突然视力模糊",
    "咯血", "呕血", "黑便", "抽搐", "意识不清", "意识模糊", "大出血",
    "肢体麻木无力", "口角歪斜",
)

# 药名 / 药类上下文（与剂量数字共现 → 判定为具体用药信息）
DRUG_CONTEXT_PAT = re.compile(
    r"二甲双胍|格列|胰岛素|布洛芬|对乙酰氨基酚|美林|泰诺|阿司匹林|硝苯地平|氨氯地平|"
    r"美托洛尔|缬沙坦|厄贝沙坦|依那普利|卡托普利|他汀|阿莫西林|头孢|阿奇霉素|奥美拉唑|"
    r"混悬液|口服液|退烧药|退热药|降压药|降糖药|抗生素"
)

# 剂量数字 + 单位（含儿科常用 ml/片/粒/滴；是否越界由药名共现门控决定）
DOSE_PAT = re.compile(
    r"\d+(\.\d+)?\s*(mg/kg|毫克/(?:公斤|kg)|mg|毫克|ml|毫升|IU|国际单位|g|克|片|粒|滴)"
)


def mentions_doctor_visit(text: str) -> bool:
    """文本是否已提示就医（就医/急诊/医院/120/急救/就诊/看医生）。"""
    return any(kw in text for kw in (
        "就医", "急诊", "医院", "120", "急救", "就诊", "看医生",
    ))
